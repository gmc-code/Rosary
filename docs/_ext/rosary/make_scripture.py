"""Build rosary_scripture.py (the verse text) from the CPDV.

Not used by Sphinx: run it only to rebuild the verse text, e.g. after
changing a reference in rosary_data.py.

    python make_scripture.py CPDV.csv

CPDV.csv is the Catholic Public Domain Version from
https://github.com/scrollmapper/bible_databases (formats/csv/CPDV.csv),
columns Book, Chapter, Verse, Text.  The CPDV is in the public domain.

rosary_data.py uses NRSV references (they match the BibleGateway links).
The CPDV follows the Vulgate, so a few passages are numbered differently;
OVERRIDE maps those NRSV references to the CPDV verses with the same text.
"""

import csv
import pprint
import re
import sys
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
import rosary_data as D  # noqa: E402

ROMAN = {'1': 'I', '2': 'II', '3': 'III'}
BOOK_NAMES = {'Psalm': 'Psalms', 'Revelation': 'Revelation of John'}

OVERRIDE = {
    'Psalm 16:10': 'Psalm 15:10',
    'Psalm 45:9': 'Psalm 44:10',
    'Psalm 132:8': 'Psalm 131:8',
    'Judith 13:18': 'Judith 13:23',
    'Judith 15:9': 'Judith 15:10',
    'Song of Solomon 2:10-11': 'Song of Solomon 2:12-13',
    'John 6:51': 'John 6:51-52',
    'John 6:54-56': 'John 6:55-57',
}

# tidy-ups of the source text
FIXES = [
    (re.compile(r'^(Bride|Groom|Chorus)( to \w+)?: '), ''),   # Song of Songs speaker labels
    (re.compile(r'through a man And '), 'through a man. And '),
    (re.compile(r' Hurry to return to me soon\.$'), ''),      # 2 Tim 4:9 run into 4:8
    (re.compile(r'^the daughters of kings in your honor\. '), ''),  # Ps 44:10 starts mid-sentence
]


def parse(ref):
    m = re.match(r'^(?:(\d) )?(.+?) (\d+):(\d+)(?:-(\d+))?$', ref)
    if not m:
        raise ValueError('cannot read reference %r' % ref)
    num, book, ch, v1, v2 = m.groups()
    book = BOOK_NAMES.get(book, book)
    if num:
        book = ROMAN[num] + ' ' + book
    return book, int(ch), int(v1), int(v2 or v1)


def main(csv_path):
    rows = csv.DictReader(open(csv_path, encoding='utf-8'))
    verses = {(r['Book'], int(r['Chapter']), int(r['Verse'])): r['Text'].strip() for r in rows}
    out = {}
    for key in D.SET_ORDER:
        for m in D.SETS[key]['mysteries']:
            for ref, _caption in m['refs']:
                cref = OVERRIDE.get(ref, ref)
                book, ch, a, b = parse(cref)
                parts = []
                for v in range(a, b + 1):
                    text = verses.get((book, ch, v))
                    if text is None:
                        raise SystemExit('missing verse %s %d:%d (for %s)' % (book, ch, v, ref))
                    for pattern, repl in FIXES:
                        text = pattern.sub(repl, text)
                    parts.append(text)
                text = ' '.join(parts)
                for pattern, repl in FIXES:
                    text = pattern.sub(repl, text)
                out[ref] = (cref if cref != ref else '', text)

    target = HERE / 'rosary_scripture.py'
    with open(target, 'w', encoding='utf-8') as f:
        f.write('"""Verse text for each reference in rosary_data.py.\n\n'
                'Catholic Public Domain Version (CPDV), public domain.\n'
                'Generated by make_scripture.py - edit that, not this file.\n\n'
                'Key: NRSV reference.  Value: (CPDV reference if numbered\n'
                'differently, else \'\', verse text).\n"""\n\n')
        f.write('TRANSLATION = "Catholic Public Domain Version"\n')
        f.write('TRANSLATION_SHORT = "CPDV"\n\n')
        f.write('TEXT = ')
        f.write(pprint.pformat(out, width=100, sort_dicts=False))
        f.write('\n')
    print('wrote %d passages to %s' % (len(out), target))


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'CPDV.csv')
